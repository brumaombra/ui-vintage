// Builders of the service worker and of its offline page (plain JavaScript: the module runs them at build time and writes the files they return)

/**
 * Options of the service worker
 * @typedef {object} ServiceWorkerOptions
 * @property {string} version Build of the app: a new build gets a new cache, and the old one is deleted
 * @property {string[]} precache Paths saved at install (the offline page, its logo and fonts, icons...)
 * @property {string} buildAssetsDir Folder of the built files, whose names change with every build ("/_nuxt/")
 * @property {string} offlinePath Page shown when a page can't load
 * @property {boolean} [selfDestroy] Remove the service worker and its caches from every device
 */

/**
 * Options of the offline page
 * @typedef {object} OfflinePageOptions
 * @property {string} name Name of the app, in the message
 * @property {string} [logo] Path of the logo shown above the message
 * @property {string} [logoDark] Path of the logo on the dark theme (the light one when missing)
 * @property {{ family: string, regular?: string, bold?: string }} [font] Font of the app and its files
 * @property {Record<string, { title: string, message: string, retry: string, note: string }>} texts Texts of each language ({name} in the message)
 */

// Prefix of the caches of the service worker (the ones of other builds are deleted on activation)
export const CACHE_PREFIX = 'uv-pwa-';

// Write the service worker: pages from the network (the offline page when there is no connection), the built files from the cache (their names change with every build), and nothing else touched (the API and the live updates always come from the network)
/** @param {ServiceWorkerOptions} options */
export const buildServiceWorker = ({ version, precache, buildAssetsDir, offlinePath, selfDestroy = false }) => {
	// Remove itself and its caches, and reload the pages it controlled so they run without it
	if (selfDestroy) {
		return `// Removes the service worker of the app and its caches
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', event => {
	event.waitUntil((async () => {
		const keys = await caches.keys();
		await Promise.all(keys.filter(key => key.startsWith(${JSON.stringify(CACHE_PREFIX)})).map(key => caches.delete(key)));
		await self.registration.unregister();
		const clients = await self.clients.matchAll({ type: 'window' });
		clients.forEach(client => client.navigate(client.url));
	})());
});`;
	}

	// The service worker
	return `// Service worker of the app (generated by @brumaombra/ui-vintage for build ${version})
const CACHE = ${JSON.stringify(CACHE_PREFIX + version)};
const PRECACHE = ${JSON.stringify(precache)};
const BUILD_ASSETS = ${JSON.stringify(buildAssetsDir)};
const BUILD_INFO = BUILD_ASSETS + 'builds/';
const OFFLINE_PAGE = ${JSON.stringify(offlinePath)};

// Save the offline page and its files, then take over at once
self.addEventListener('install', event => {
	event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

// Delete the caches of the other builds, then control the open pages
self.addEventListener('activate', event => {
	event.waitUntil(caches.keys()
		.then(keys => Promise.all(keys.filter(key => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE).map(key => caches.delete(key))))
		.then(() => self.clients.claim()));
});

// A file from the cache, or from the network (kept for next time when it loads)
const fromCacheFirst = async request => {
	const cache = await caches.open(CACHE);
	const cached = await cache.match(request);
	if (cached) return cached;
	const response = await fetch(request);
	if (response.ok) cache.put(request, response.clone());
	return response;
};

// Answer the requests of the app (only GET requests of its own origin: everything else goes to the network untouched)
self.addEventListener('fetch', event => {
	const { request } = event;
	if (request.method !== 'GET') return;
	const url = new URL(request.url);
	if (url.origin !== self.location.origin) return;

	// Pages: from the network, the offline page when there is no connection
	if (request.mode === 'navigate') {
		event.respondWith(fetch(request).catch(() => caches.match(OFFLINE_PAGE)));
		return;
	}

	// Built files: from the cache (not the build info, which tells the app a new build is out)
	if (url.pathname.startsWith(BUILD_ASSETS) && !url.pathname.startsWith(BUILD_INFO)) {
		event.respondWith(fromCacheFirst(request));
		return;
	}

	// Files saved at install: from the cache
	if (PRECACHE.includes(url.pathname)) {
		event.respondWith(caches.match(request).then(cached => cached || fetch(request)));
	}
});`;
};

// Escape a text for HTML
/** @param {string} text */
const escapeHtml = text => text.replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', '\'': '&#39;' })[character]);

// Write the offline page: self-contained (it has no network), in the colors of the library, light or dark like the app, in the language of the page that couldn't load
/** @param {OfflinePageOptions} options */
export const buildOfflinePage = ({ name, logo, logoDark, font, texts }) => {
	const fallbackLanguage = texts.en ? 'en' : Object.keys(texts)[0];
	const english = texts[fallbackLanguage];
	const fontFaces = font ? [[400, font.regular], [700, font.bold]].filter(([, file]) => file).map(([weight, file]) => `@font-face { font-family: ${JSON.stringify(font.family)}; font-weight: ${weight}; src: url(${JSON.stringify(file)}) format('woff2'); }`).join('\n\t\t') : '';
	const fontFamily = `${font ? `${JSON.stringify(font.family)}, ` : ''}ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace`;

	return `<!doctype html>
<html lang="${fallbackLanguage}">
<head>
	<meta charset="utf-8">
	<meta name="viewport" content="width=device-width, initial-scale=1">
	<meta name="robots" content="noindex">
	<title>${escapeHtml(name)}</title>
	<script>
		// Dark like the app: the theme picked in the app, or the one of the system
		try {
			const theme = localStorage.getItem('theme');
			const dark = theme === 'dark' || (theme !== 'light' && matchMedia('(prefers-color-scheme: dark)').matches);
			document.documentElement.classList.add(dark ? 'dark' : 'light');
		} catch {}
	</script>
	<style>
		${fontFaces}

		/* Colors of the library, light and dark */
		:root { --background: #fafafa; --foreground: #1b222d; --muted: #606976; --primary: #f7931a; --primary-foreground: #1b222d; color-scheme: light; }
		:root.dark { --background: #0f1318; --foreground: #eef3f8; --muted: #97a2b2; --primary: #f7a23c; --primary-foreground: #1b222d; color-scheme: dark; }

		* { box-sizing: border-box; }
		body { margin: 0; min-height: 100dvh; display: flex; align-items: center; justify-content: center; padding: 24px; background: var(--background); color: var(--foreground); font-family: ${fontFamily}; word-spacing: -0.25em; text-align: center; -webkit-font-smoothing: antialiased; }
		main { width: 100%; max-width: 22rem; }
		img { width: 72px; height: 72px; object-fit: contain; }
		:root.dark .logo-light, :root.light .logo-dark { display: none; }
		h1 { margin: 24px 0 8px; font-size: 1.25rem; font-weight: 700; }
		p { margin: 0; color: var(--muted); font-size: 0.875rem; line-height: 1.6; }
		button { margin-top: 24px; width: 100%; height: 48px; border: 0; border-radius: 0.25rem; background: var(--primary); color: var(--primary-foreground); font: inherit; font-size: 0.875rem; font-weight: 700; word-spacing: inherit; cursor: pointer; touch-action: manipulation; }
		button:focus-visible { outline: 3px solid color-mix(in oklab, var(--primary) 45%, transparent); outline-offset: 2px; }
		.note { margin-top: 12px; font-size: 0.75rem; }
	</style>
</head>
<body>
	<main>
		${logo && logoDark ? `<img class="logo-light" src="${escapeHtml(logo)}" alt=""><img class="logo-dark" src="${escapeHtml(logoDark)}" alt="">` : logo ? `<img src="${escapeHtml(logo)}" alt="">` : ''}
		<h1 data-text="title">${escapeHtml(english.title)}</h1>
		<p data-text="message">${escapeHtml(english.message.replace('{name}', name))}</p>
		<button type="button" data-text="retry" onclick="location.reload()">${escapeHtml(english.retry)}</button>
		<p class="note" data-text="note">${escapeHtml(english.note)}</p>
	</main>
	<script>
		// Texts of each language, and the name of the app
		const TEXTS = ${JSON.stringify(texts).replace(/</g, '\\u003c')};
		const NAME = ${JSON.stringify(name).replace(/</g, '\\u003c')};

		// The language of the page that couldn't load (its address starts with it), or of the browser
		const fromPath = location.pathname.split('/')[1];
		const fromBrowser = (navigator.language || '').slice(0, 2);
		const language = TEXTS[fromPath] ? fromPath : TEXTS[fromBrowser] ? fromBrowser : ${JSON.stringify(fallbackLanguage)};

		// Show the texts of that language
		document.documentElement.lang = language;
		document.querySelectorAll('[data-text]').forEach(element => {
			element.textContent = TEXTS[language][element.dataset.text].replace('{name}', NAME);
		});

		// Reload once the connection is back
		window.addEventListener('online', () => location.reload());
	</script>
</body>
</html>`;
};